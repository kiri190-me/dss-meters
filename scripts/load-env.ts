/**
 * .env.local 을 읽는다 — 없으면 그냥 넘어간다.
 *
 * 개발 PC 에서는 그 파일에 DB 접속과 cafe24 SMTP 비밀번호가 들어 있다.
 * **NAS 의 도구 컨테이너에는 그 파일이 없다.** `.dockerignore` 가 `.env*` 를
 * 통째로 막기 때문이고, 그게 맞다 — 이미지는 파일로 복사되어 돌아다닌다.
 * 거기서는 같은 값이 컨테이너 환경변수로 들어온다(compose 의 `env_file`).
 *
 * ── 왜 process.loadEnvFile 을 직접 부르지 않나 ────────────────────────
 *
 * Node 내장 `loadEnvFile` 은 dotenv 와 달리 **파일이 없으면 던진다**(ENOENT).
 * 스크립트마다 그 줄을 그대로 두면 컨테이너에서 **첫 줄에 죽는다** — 환경변수를
 * 아무리 잘 넣어 주어도 그것을 읽기 전이다. 증상은 알림이 나가야 할 날 아침에
 * "메일이 안 왔다" 로만 나타난다.
 *
 * 그렇다고 컨테이너용으로 빈 `.env.local` 을 이미지에 넣지는 않는다.
 * 비밀값 파일처럼 생긴 빈 파일이 남으면 누군가 채워 넣고 싶어진다.
 *
 * ── 개발 PC 동작은 한 글자도 바뀌지 않는다 ───────────────────────────
 *
 * 파일이 있으면 전과 똑같이 읽는다. 그리고 **이미 들어와 있는 환경변수를
 * 덮어쓰지 않는다** — Node 의 loadEnvFile 이 원래 그렇게 동작한다(2026-09-16
 * 실측: 환경에 있던 값이 이기고, 파일에만 있는 값만 채워진다). 그래서
 * `DATABASE_URL=... npm run send-notify` 처럼 앞에 붙여 주는 방식도 그대로 산다.
 */
