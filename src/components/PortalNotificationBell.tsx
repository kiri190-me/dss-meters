import { NotificationBell } from "@dss/ui";

import { fetchPortalNotifications } from "@/lib/auth/oidc";

/**
 * 머리말의 알림 종 — **다른 시스템들의** 알림을 그린다.
 *
 * 사내 시스템이 여섯인데(A/S · 포털 · 계측기 · 개선요청 · PO/내자 · 휴가) 종은
 * A/S 에만 있었다. 「어느 시스템에 있든 같은 알림을 본다」를 위해 포털이 모든
 * 시스템에 물어 합쳐 주는 통로를 열었고, 이 조각이 그것을 이 사이트에
 * 끌어온다(부르는 법: dss-auth/docs/사이트-알림-통로.md).
 *
 * ── 🔴 왜 **서버**에서 가져오나 (브라우저가 아니라) ──────────────────────
 * 자격증명이 `client_secret` 이라 브라우저에서는 부를 수 없다. 브라우저에서
 * 가져오려면 이 사이트 안에 중계 통로(route handler)를 하나 더 두고, 거기서
 * 세션을 다시 검증하고, 종을 클라이언트 조각으로 바꾸고, 그 왕복이 도는 동안의
 * 상태까지 다뤄야 한다 — **시크릿을 다루는 자리를 하나 더 만드는** 일이다.
 * 서버에서 부르면 시크릿은 이 프로세스 밖으로 나가지 않고, 종은 지금처럼
 * 자바스크립트 없이도 열리는 서버 조각(@dss/ui 의 `<details>`)으로 남는다.
 *
 * 🔴 그 대신 **모든 화면 이동이 이 왕복만큼 느려지는** 것을 막아야 한다.
 *    그래서 부르는 쪽((internal)/layout.tsx)이 이 조각을 `<Suspense>` 로
 *    감싼다 — 머리말과 본문은 먼저 뜨고 종만 나중에 흘러 들어온다. 포털이
 *    느리거나 죽어도 사람이 기다리는 시간은 늘지 않는다. 왕복 자체에도 상한이
 *    걸려 있다(oidc.ts 의 NOTIFICATIONS_TIMEOUT_MS).
 *
 * ── 🔴 다시 묻는 주기는 두지 않는다 ─────────────────────────────────────
 * 브라우저에서 몇 초마다 다시 묻는 장치를 붙이지 않았다. 포털이 이미 30초
 * 캐시를 들고 있어 그보다 자주 물으면 **같은 답**을 받고, 그 장치를 붙이는
 * 순간 위에서 피한 중계 통로가 도로 필요해진다. 종은 화면을 새로 열 때
 * 갱신된다.
 *
 * ── 확인(onAcknowledge)을 넘기지 않는 이유 ──────────────────────────────
 * 여기 오는 알림은 **전부 남의 시스템 것**이다. 「확인했다」를 적을 수 있는
 * 곳은 그 알림을 만든 시스템뿐이고, 이 사이트에는 적을 자리가 없다. 줄을
 * 누르면 그 시스템의 화면으로 건너가고, 거기서 일을 마치면 다음 왕복에서
 * 목록이 줄어든다.
 */
export async function PortalNotificationBell({ subject }: { subject: string }) {
  // 🔴 던지지 않는다. 포털이 죽었든 우리를 거절했든 빈 목록이 온다.
  const feed = await fetchPortalNotifications(subject);

  // 🔴 이 사이트에는 **자체 알림이 없다.** (2026-09-21 확인 — 교정 기한 알림은
  //    메일로만 나가고 화면에 쌓이는 종이 없다. lib/mail/notify-mail.ts ·
  //    docs/NOTIFY.md.) 그래서 받은 것이 곧 전부다. 자체 알림이 생기면 여기서
  //    `[...내것, ...feed.items]` 로 이어 붙이고 개수도 더한다 — 포털은 부른
  //    사이트 자신의 알림을 빼고 주기 때문이다.
  //
  // 개수는 포털이 센 값 그대로 넘긴다(다시 세지 않는다 — @dss/ui README 7절).
  // 목록이 비면 그 조각이 스스로 null 이라 머리말에 종 자체가 생기지 않는다.
  //
  // ── 🔴 `className="ml-auto"` 한 낱말이 이 사이트에만 있다 ───────────────
  // 종의 펼친 목록은 종에 **오른쪽 끝을 맞춰** 왼쪽으로 펼쳐지고(그쪽 CSS 의
  // `right: 0`) 폭이 폰에서 320px 이다. 그래서 종은 줄의 **맨 오른쪽 끝**에
  // 있어야 목록이 화면 안에 들어온다.
  //
  // 그런데 이 머리말의 오른쪽 묶음은 폰(<640px)에서 `w-full` 이고 오른쪽
  // 정렬을 **끈다**(2026-09-18 사용자 폰 사진 — "둘째 줄이 오른쪽으로 쏠려
  // 왼쪽이 텅 비었다"). 그 판단은 그대로 두어야 하는데, 그러면 줄 끝에 놓은
  // 종도 왼쪽으로 딸려 와 목록의 왼쪽이 잘린다(관리자·일본어에서는 묶음이
  // 제 안에서 줄을 바꿔 종이 둘째 줄 **맨 왼쪽**에 선다 — 그때는 목록이 거의
  // 통째로 화면 밖이다). `ml-auto` 는 그 줄에 남는 자리를 전부 먹어 종만
  // 오른쪽 끝으로 보낸다.
  //
  // 🔴 넓은 화면(≥640px)에서는 아무 일도 하지 않는다 — 그 묶음이 `w-auto`
  //    라 제 안에 남는 자리가 0 이고, 자동 여백은 남는 자리를 나눠 가질 뿐이다.
  // 🔴 래퍼 <div> 를 두는 대신 조각에 직접 거는 이유: 알림이 없으면 이 조각이
  //    **스스로 null** 이라 머리말에서 통째로 사라져야 하는데, 감싸면 빈 flex
  //    항목과 그 앞 여백(gap-3 12px)이 남아 머리말이 예전과 달라진다.
  //
  // 🔴 colorScheme 은 넘기지 않는다. 이 사이트는 globals.css 에서
  //    color-scheme: light 로 고정이고, 기본값 "host" 는 조상에 .dark 가 있을
  //    때만 어두워지므로 그대로 두는 것이 옳다(@dss/ui README 4·7절).
  return <NotificationBell items={feed.items} count={feed.count} className="ml-auto" />;
}
